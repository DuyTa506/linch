from __future__ import annotations

from copy import deepcopy
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Any
from uuid import uuid4

from linch.durability import InboxDelivery, decode_inbox_message, encode_inbox_delivery
from linch.errors import ConfigError
from linch.sessions.tasks import CreateTaskInput, Task, TaskPatch
from linch.types import Message, message_from_dict, message_to_dict

from .store import (
    ProviderViewSnapshot,
    SessionRecord,
    StoredMessage,
    snapshot_from_dict,
    snapshot_to_dict,
)


def now_iso() -> str:
    """Return the current UTC timestamp in ISO 8601 form.

    Returns:
        Current UTC timestamp as an ISO-formatted string.
    """

    return datetime.now(UTC).isoformat()


def _copy_message(message: Message) -> Message:
    """Copy the full message wire graph while retaining the shared strict codec."""

    return message_from_dict(deepcopy(message_to_dict(message)))


@dataclass(slots=True)
class _InboxRow:
    digest: str
    message_json: str | None
    source: str | None
    metadata_json: str | None
    message_seq: int | None = None


class InMemorySessionStore:
    """Store sessions, messages, inbox rows, and tasks in process memory.

    The store is intended for tests and development. Mutations are visible
    immediately within the process but are not durable across restarts.
    Inputs and returned session, message, and task graphs are detached copies.
    """

    def __init__(self) -> None:
        """Initialize an empty process-local session store."""

        self._sessions: dict[str, SessionRecord] = {}
        self._messages: dict[str, list[StoredMessage]] = {}
        self._snapshots: dict[str, dict[str, Any]] = {}
        self._tasks: dict[str, dict[str, Task]] = {}
        self._task_counter: dict[str, int] = {}
        # Process-local implementation of the durable-inbox protocol.  It has
        # identical dedupe/commit semantics but intentionally no restart
        # guarantee.
        self._inbox: dict[str, dict[str, _InboxRow]] = {}

    async def create(
        self, *, id: str | None = None, meta: dict[str, object] | None = None
    ) -> SessionRecord:
        """Create a session or return the existing record for an explicit ID.

        Args:
            id: Optional stable ID; omitted IDs are generated by the store.
            meta: Initial application-defined session metadata.

        Returns:
            The created or already-existing session record.
        """

        sid = id or str(uuid4())
        existing = self._sessions.get(sid)
        if existing is not None:
            return deepcopy(existing)
        ts = now_iso()
        record = SessionRecord(id=sid, created_at=ts, updated_at=ts, meta=deepcopy(meta or {}))
        self._sessions[sid] = record
        self._messages.setdefault(sid, [])
        self._tasks.setdefault(sid, {})
        self._task_counter.setdefault(sid, self._next_task_id(sid))
        self._inbox.setdefault(sid, {})
        return deepcopy(record)

    async def create_if_absent(
        self, *, id: str, meta: dict[str, object] | None = None
    ) -> SessionRecord | None:
        """Atomically create a specifically named session, or return ``None``.

        This is an optional capability used by portable session forking.  The
        method contains no suspension point, so lookup and insertion are one
        event-loop-atomic operation.

        Args:
            id: Stable session ID to reserve.
            meta: Initial application-defined session metadata.

        Returns:
            The newly created record, or ``None`` when the ID already exists.
        """

        if id in self._sessions:
            return None
        return await self.create(id=id, meta=meta)

    async def load(self, id: str) -> SessionRecord | None:
        """Load a session record by ID.

        Args:
            id: Session identifier to look up.

        Returns:
            The current session record, or ``None`` when the ID is unknown.
        """

        return deepcopy(self._sessions.get(id))

    async def load_messages(self, id: str) -> list[StoredMessage]:
        """Load stored messages in ascending sequence order.

        Args:
            id: Session identifier whose messages should be loaded.

        Returns:
            Detached stored-message copies ordered by sequence number.
        """

        return [
            StoredMessage(
                seq=row.seq,
                appended_at=row.appended_at,
                message=_copy_message(row.message),
            )
            for row in self._messages.get(id, [])
        ]

    async def append_messages(self, id: str, messages: list[Message]) -> list[StoredMessage]:
        """Atomically append messages in input order and assign consecutive sequences.

        Args:
            id: Session identifier receiving the messages.
            messages: Messages to append in provider order.

        Returns:
            Stored rows for the appended messages in input order.

        Raises:
            KeyError: If the session does not exist.
        """

        if id not in self._sessions:
            raise KeyError(f"session not found: {id}")
        ts = now_iso()
        bucket = self._messages[id]
        stored = [
            StoredMessage(
                seq=len(bucket) + index,
                appended_at=ts,
                message=_copy_message(message),
            )
            for index, message in enumerate(messages, start=1)
        ]
        result = deepcopy(stored)
        bucket.extend(stored)
        rec = self._sessions[id]
        rec.updated_at = ts
        return result

    async def enqueue_inbox(self, id: str, delivery: InboxDelivery) -> None:
        """Enqueue one inbox delivery with delivery-ID/digest deduplication.

        Args:
            id: Session identifier receiving the delivery.
            delivery: Delivery receipt and message payload to enqueue.

        Repeating the same delivery ID with the same digest is an idempotent
        no-op; a different digest is rejected.

        Raises:
            KeyError: If the session does not exist.
            ConfigError: If the delivery ID conflicts with a stored digest.
        """

        if id not in self._sessions:
            raise KeyError(f"session not found: {id}")
        bucket = self._inbox.setdefault(id, {})
        existing = bucket.get(delivery.delivery_id)
        if existing is not None:
            if existing.digest != delivery.digest:
                raise ConfigError(
                    f"conflicting inbox delivery {delivery.delivery_id!r} for session {id!r}"
                )
            return
        message_json, source, metadata_json = encode_inbox_delivery(delivery)
        bucket[delivery.delivery_id] = _InboxRow(
            digest=delivery.digest,
            message_json=message_json,
            source=source,
            metadata_json=metadata_json,
        )

    async def commit_inbox(self, id: str, *, after_seq: int) -> list[StoredMessage]:
        """Atomically commit pending inbox rows and return messages after a cursor.

        Args:
            id: Session identifier whose inbox should be committed.
            after_seq: Exclusive message sequence cursor for returned rows.

        Returns:
            Stored messages with sequence numbers greater than ``after_seq``.

        Raises:
            KeyError: If the session does not exist or a pending message omits
                a required field.
            ConfigError: If ``after_seq`` is invalid, a pending row has no
                message payload, or the decoded payload is not an object.
            json.JSONDecodeError: If a pending message's JSON is malformed.
            TypeError: If a pending message field has an incompatible shape.
            ValueError: If a pending message contains an unknown content-block
                type.
        """

        if id not in self._sessions:
            raise KeyError(f"session not found: {id}")
        if isinstance(after_seq, bool) or not isinstance(after_seq, int) or after_seq < 0:
            raise ConfigError("after_seq must be a non-negative integer")

        ts = now_iso()
        messages = self._messages[id]
        pending: list[tuple[_InboxRow, Message]] = []
        for row in self._inbox.setdefault(id, {}).values():
            if row.message_seq is not None:
                continue
            if row.message_json is None:  # pragma: no cover - internal corruption guard
                raise ConfigError("pending inbox delivery has no message payload")
            pending.append((row, decode_inbox_message(row.message_json)))
        for row, message in pending:
            seq = len(messages) + 1
            messages.append(StoredMessage(seq=seq, appended_at=ts, message=message))
            row.message_seq = seq
            # Keep the small receipt forever, discard the potentially large
            # source payload after it is represented in message history.
            row.message_json = None
            row.source = None
            row.metadata_json = None
        if messages and messages[-1].seq > after_seq:
            self._sessions[id].updated_at = ts
        return deepcopy([row for row in messages if row.seq > after_seq])

    async def save_provider_snapshot(self, id: str, snapshot: ProviderViewSnapshot) -> None:
        """Save a wire-normalized compacted provider-view snapshot.

        Args:
            id: Session identifier owning the snapshot.
            snapshot: Provider projection and message watermark to store.
        """

        # Round-trip through the wire form so behavior matches the persisted stores.
        self._snapshots[id] = snapshot_to_dict(snapshot)

    async def load_provider_snapshot(self, id: str) -> ProviderViewSnapshot | None:
        """Load a previously saved provider-view snapshot.

        Args:
            id: Session identifier whose snapshot should be loaded.

        Returns:
            The stored snapshot, or ``None`` when none has been saved.
        """

        raw = self._snapshots.get(id)
        return snapshot_from_dict(raw) if raw is not None else None

    async def update_meta(self, id: str, meta: dict[str, object]) -> SessionRecord:
        """Merge metadata into a session and update its timestamp.

        Args:
            id: Session identifier whose metadata should be updated.
            meta: Metadata keys and values to merge.

        Returns:
            The updated session record.

        Raises:
            KeyError: If the session does not exist.
        """

        rec = self._sessions[id]
        rec.meta.update(deepcopy(meta))
        rec.updated_at = now_iso()
        return deepcopy(rec)

    async def set_invoked_skills(self, id: str, skills: list[dict[str, object]]) -> None:
        """Replace persisted invoked-skill records for a session.

        Args:
            id: Session identifier whose records should be replaced.
            skills: Skill records to store.

        Raises:
            KeyError: If the session does not exist.
        """

        rec = self._sessions[id]
        rec.invoked_skills = deepcopy(skills)
        rec.updated_at = now_iso()

    async def list(self, *, limit: int | None = None, offset: int = 0) -> list[SessionRecord]:
        """List sessions ordered by descending update timestamp.

        Args:
            limit: Maximum number of records, or ``None`` for all records.
            offset: Number of newest records to skip.

        Returns:
            Matching session records in newest-updated-first order.
        """

        rows = sorted(self._sessions.values(), key=lambda rec: rec.updated_at, reverse=True)
        if offset:
            rows = rows[offset:]
        if limit is not None:
            rows = rows[:limit]
        return deepcopy(rows)

    async def delete(self, id: str) -> None:
        """Delete a session and all process-local state associated with it.

        Args:
            id: Session identifier to delete.

        Deleting an unknown ID is an idempotent no-op.
        """

        self._sessions.pop(id, None)
        self._messages.pop(id, None)
        self._snapshots.pop(id, None)
        self._tasks.pop(id, None)
        self._task_counter.pop(id, None)
        self._inbox.pop(id, None)

    async def create_task(self, session_id: str, input: CreateTaskInput) -> Task:
        """Create a pending task with the next session-local numeric ID.

        Args:
            session_id: Session that owns the task.
            input: Task fields to persist.

        Returns:
            The newly created task.

        Raises:
            KeyError: If the session does not exist.
        """

        if session_id not in self._sessions:
            raise KeyError(f"session not found: {session_id}")
        task_id = str(self._task_counter.get(session_id, self._next_task_id(session_id)))
        self._task_counter[session_id] = int(task_id) + 1
        ts = now_iso()
        task = Task(
            id=task_id,
            session_id=session_id,
            subject=input.subject,
            description=input.description,
            active_form=input.active_form,
            status="pending",
            metadata=deepcopy(input.metadata or {}),
            created_at=ts,
            updated_at=ts,
        )
        bucket = self._tasks.setdefault(session_id, {})
        for existing in bucket.values():
            if task_id in existing.blocks:
                task.blocked_by.append(existing.id)
            if task_id in existing.blocked_by:
                task.blocks.append(existing.id)
        bucket[task_id] = task
        self._sessions[session_id].updated_at = ts
        return deepcopy(task)

    def _next_task_id(self, session_id: str) -> int:
        numeric_ids = (
            int(task_id) for task_id in self._tasks.get(session_id, {}) if task_id.isdecimal()
        )
        return max(numeric_ids, default=0) + 1

    async def get_task(self, session_id: str, task_id: str) -> Task | None:
        """Load one task by session and task ID.

        Args:
            session_id: Session that owns the task.
            task_id: Task identifier to look up.

        Returns:
            The task, or ``None`` when it does not exist.
        """

        return deepcopy(self._tasks.get(session_id, {}).get(task_id))

    async def list_tasks(self, session_id: str) -> list[Task]:
        """List a session's tasks in ascending numeric task-ID order.

        Args:
            session_id: Session whose tasks should be listed.

        Returns:
            Tasks in deterministic task-ID order.
        """

        tasks = self._tasks.get(session_id, {})
        return deepcopy(sorted(tasks.values(), key=lambda t: int(t.id)))

    async def update_task(self, session_id: str, task_id: str, patch: TaskPatch) -> Task | None:
        """Apply a partial task update and dependency-edge changes.

        Args:
            session_id: Session that owns the task.
            task_id: Task identifier to update.
            patch: Fields and dependency edges to change.

        Returns:
            The updated task, or ``None`` when it does not exist or is deleted.
        """

        task = self._tasks.get(session_id, {}).get(task_id)
        if task is None:
            return None
        if patch.status == "deleted":
            await self.delete_task(session_id, task_id)
            return None

        if patch.subject is not None:
            task.subject = patch.subject
        if patch.description is not None:
            task.description = patch.description
        if patch.active_form is not None:
            task.active_form = patch.active_form
        if patch.status is not None and patch.status != "deleted":
            task.status = patch.status
        if patch.owner is not None:
            task.owner = patch.owner
        if patch.metadata is not None:
            for key, value in patch.metadata.items():
                if value is None:
                    task.metadata.pop(key, None)
                else:
                    task.metadata[key] = deepcopy(value)

        bucket = self._tasks[session_id]
        if patch.remove_blocks:
            task.blocks = [tid for tid in task.blocks if tid not in patch.remove_blocks]
            for tid in patch.remove_blocks:
                if (target := bucket.get(tid)) is not None:
                    target.blocked_by = [bid for bid in target.blocked_by if bid != task_id]
        if patch.remove_blocked_by:
            task.blocked_by = [tid for tid in task.blocked_by if tid not in patch.remove_blocked_by]
            for tid in patch.remove_blocked_by:
                if (source := bucket.get(tid)) is not None:
                    source.blocks = [bid for bid in source.blocks if bid != task_id]

        for tid in patch.add_blocks or []:
            if tid not in task.blocks:
                task.blocks.append(tid)
            if (target := bucket.get(tid)) is not None and task_id not in target.blocked_by:
                target.blocked_by.append(task_id)
        for tid in patch.add_blocked_by or []:
            if tid not in task.blocked_by:
                task.blocked_by.append(tid)
            if (source := bucket.get(tid)) is not None and task_id not in source.blocks:
                source.blocks.append(task_id)

        task.updated_at = now_iso()
        self._sessions[session_id].updated_at = task.updated_at
        return deepcopy(task)

    async def delete_task(self, session_id: str, task_id: str) -> bool:
        """Delete a task and remove references to it from other tasks.

        Args:
            session_id: Session that owns the task.
            task_id: Task identifier to delete.

        Returns:
            ``True`` when a task was deleted, otherwise ``False``.
        """

        bucket = self._tasks.get(session_id, {})
        existed = task_id in bucket
        bucket.pop(task_id, None)
        if existed:
            for task in bucket.values():
                task.blocks = [tid for tid in task.blocks if tid != task_id]
                task.blocked_by = [tid for tid in task.blocked_by if tid != task_id]
            self._sessions[session_id].updated_at = now_iso()
        return existed

    async def claim_task(self, session_id: str, task_id: str, owner: str) -> Task | None:
        """Atomically claim one pending, unowned task for an owner.

        Args:
            session_id: Session that owns the task.
            task_id: Task identifier to claim.
            owner: Owner identity to record on success.

        Returns:
            The claimed task, or ``None`` when it is unavailable.
        """

        task = self._tasks.get(session_id, {}).get(task_id)
        if task is None or task.owner is not None or task.status != "pending":
            return None
        task.owner = owner
        task.updated_at = now_iso()
        self._sessions[session_id].updated_at = task.updated_at
        return deepcopy(task)

    async def ready_tasks(self, session_id: str) -> list[Task]:
        """List pending, unowned tasks whose dependencies are complete.

        Args:
            session_id: Session whose ready tasks should be listed.

        Returns:
            Ready tasks in ascending numeric task-ID order.
        """

        bucket = self._tasks.get(session_id, {})
        out: list[Task] = []
        for task in sorted(bucket.values(), key=lambda t: int(t.id)):
            if task.status != "pending" or task.owner is not None:
                continue
            if all(
                (dep := bucket.get(bid)) is not None and dep.status == "completed"
                for bid in task.blocked_by
            ):
                out.append(task)
        return deepcopy(out)

    async def release_task(self, session_id: str, task_id: str) -> Task | None:
        """Release a task owner and reset unfinished tasks to pending.

        Args:
            session_id: Session that owns the task.
            task_id: Task identifier to release.

        Returns:
            The released task, or ``None`` when it does not exist. Completed
            tasks are returned unchanged.
        """

        task = self._tasks.get(session_id, {}).get(task_id)
        if task is None:
            return None
        if task.status == "completed":
            return deepcopy(task)
        task.owner = None
        task.status = "pending"
        task.updated_at = now_iso()
        self._sessions[session_id].updated_at = task.updated_at
        return deepcopy(task)

    async def close(self) -> None:
        """Close the process-local store; this implementation has no resources."""

        return None
