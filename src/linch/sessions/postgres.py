# ── DDL ─────────────────────────────────────────────────────────────────────

_SCHEMA = """
CREATE TABLE IF NOT EXISTS sessions (
    id          TEXT PRIMARY KEY,
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL,
    meta        TEXT NOT NULL DEFAULT '{}',
    invoked_skills TEXT NOT NULL DEFAULT '[]',
    last_message_seq BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS messages (
    session_id  TEXT NOT NULL,
    seq         INTEGER NOT NULL,
    appended_at TEXT NOT NULL,
    message     TEXT NOT NULL,
    PRIMARY KEY (session_id, seq)
);

CREATE TABLE IF NOT EXISTS task_counters (
    session_id  TEXT PRIMARY KEY,
    next_id     INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS tasks (
    session_id   TEXT NOT NULL,
    id           TEXT NOT NULL,
    subject      TEXT NOT NULL,
    description  TEXT NOT NULL,
    active_form  TEXT,
    status       TEXT NOT NULL,
    owner        TEXT,
    metadata_json TEXT NOT NULL,
    created_at   TEXT NOT NULL,
    updated_at   TEXT NOT NULL,
    PRIMARY KEY (session_id, id)
);

CREATE TABLE IF NOT EXISTS task_edges (
    session_id   TEXT NOT NULL,
    from_task_id TEXT NOT NULL,
    to_task_id   TEXT NOT NULL,
    kind         TEXT NOT NULL DEFAULT 'blocks',
    PRIMARY KEY (session_id, from_task_id, to_task_id)
);

CREATE TABLE IF NOT EXISTS session_snapshots (
    session_id  TEXT PRIMARY KEY,
    snapshot    TEXT NOT NULL,
    updated_at  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS session_inbox (
    session_id    TEXT NOT NULL,
    delivery_id   TEXT NOT NULL,
    inbox_seq     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    digest        TEXT NOT NULL,
    enqueued_at   TEXT NOT NULL,
    message       TEXT,
    source        TEXT,
    metadata_json TEXT,
    message_seq   INTEGER,
    PRIMARY KEY (session_id, delivery_id),
    UNIQUE (session_id, inbox_seq)
);

CREATE INDEX IF NOT EXISTS session_inbox_pending_idx
    ON session_inbox (session_id, message_seq, inbox_seq);

CREATE TABLE IF NOT EXISTS session_offloads (
    session_id  TEXT NOT NULL,
    path        TEXT NOT NULL,
    content     TEXT NOT NULL,
    PRIMARY KEY (session_id, path)
);
"""


# ── Store ────────────────────────────────────────────────────────────────────


class PostgresSessionStore:
    """Session store backed by Postgres via ``asyncpg``.

    All operations use a shared connection pool.  Concurrent coroutines
    (including subagents) acquire independent connections and run in parallel —
    no single-connection serialisation bottleneck.

    The schema is created automatically on first use (``CREATE TABLE IF NOT
    EXISTS``).  No migration tool is required; simply point at an empty DB.

    Args:
        dsn: PostgreSQL connection string (e.g. "postgresql://user:pw@host/dbname").
        pool: Host-owned asyncpg pool to reuse; when set, dsn is ignored.
        min_size: Minimum pool connections.
        max_size: Maximum pool connections.
    """

    def __init__(
        self,
        dsn: str,
        *,
        pool: Any = None,
        min_size: int = 1,
        max_size: int = 10,
    ) -> None:
        """Configure a Postgres-backed session store.

        Args:
            dsn: PostgreSQL connection string; ignored when ``pool`` is supplied.
            pool: Optional host-owned asyncpg pool; the store never closes it.
            min_size: Minimum size for a store-created connection pool.
            max_size: Maximum size for a store-created connection pool.
        """

        _import_asyncpg()  # fail fast with install hint if asyncpg missing
        self._dsn = dsn
        self._pool: Any = pool
        self._owns_pool = pool is None
        self._min_size = min_size
        self._max_size = max_size
        self._initialized = False
        self._init_lock = asyncio.Lock()

    async def _ensure(self) -> Any:
        return await ensure_pool(
            self,
            _SCHEMA,
            _import_asyncpg,
            schema_key="sessions",
            tables=(
                "sessions",
                "messages",
                "task_counters",
                "tasks",
                "task_edges",
                "session_snapshots",
                "session_inbox",
                "session_offloads",
            ),
            required_columns={"sessions": ("last_message_seq",)},
        )

    # ── SessionStore protocol ────────────────────────────────────────────────

    async def create(
        self, *, id: str | None = None, meta: dict[str, object] | None = None
    ) -> SessionRecord:
        """Create a session or return the existing record for an explicit ID.

        Args:
            id: Optional stable ID; omitted IDs are generated by the store.
            meta: Initial application-defined session metadata.

        Returns:
            The created or already-existing session record after the insert
            transaction has committed.
        """

        pool = await self._ensure()
        _meta = meta or {}
        sid = id or str(uuid4())
        ts = now_iso()
        async with pool.acquire() as conn:
            async with conn.transaction():
                # Idempotent even when two processes create the same explicit
                # id concurrently.  The winner's record is returned to both.
                await conn.execute(
                    "INSERT INTO sessions (id, created_at, updated_at, meta, invoked_skills) "
                    "VALUES ($1, $2, $3, $4, $5) ON CONFLICT (id) DO NOTHING",
                    sid,
                    ts,
                    ts,
                    json.dumps(_meta),
                    "[]",
                )
                await conn.execute(
                    "INSERT INTO task_counters (session_id, next_id) "
                    "SELECT $1, COALESCE(MAX(id::BIGINT), 0) + 1 FROM tasks "
                    "WHERE session_id = $1 AND id ~ '^[0-9]+$' "
                    "ON CONFLICT DO NOTHING",
                    sid,
                )
                row = await conn.fetchrow(
                    "SELECT id, created_at, updated_at, meta, invoked_skills "
                    "FROM sessions WHERE id = $1",
                    sid,
                )
        if row is None:  # pragma: no cover - transaction invariant
            raise RuntimeError(f"session disappeared during create: {sid}")
        return _record(row)

    async def create_if_absent(
        self, *, id: str, meta: dict[str, object] | None = None
    ) -> SessionRecord | None:
        """Atomically create a named session, or return ``None`` if it exists.

        This is an optional capability used by session forking to prove that
        this caller owns the destination id before copying any history.  The
        ``RETURNING`` row comes only from this transaction's successful insert;
        no select-then-insert ownership inference is involved.

        Args:
            id: Stable session ID to reserve.
            meta: Initial application-defined session metadata.

        Returns:
            The newly inserted record, or ``None`` when the ID already exists.
        """
        pool = await self._ensure()
        ts = now_iso()
        payload = json.dumps(meta or {})
        async with pool.acquire() as conn:
            async with conn.transaction():
                row = await conn.fetchrow(
                    """
                    INSERT INTO sessions (
                        id, created_at, updated_at, meta, invoked_skills
                    ) VALUES ($1, $2, $3, $4, $5)
                    ON CONFLICT (id) DO NOTHING
                    RETURNING id, created_at, updated_at, meta, invoked_skills
                    """,
                    id,
                    ts,
                    ts,
                    payload,
                    "[]",
                )
                if row is None:
                    return None
                await conn.execute(
                    "INSERT INTO task_counters (session_id, next_id) "
                    "SELECT $1, COALESCE(MAX(id::BIGINT), 0) + 1 FROM tasks "
                    "WHERE session_id = $1 AND id ~ '^[0-9]+$' "
                    "ON CONFLICT DO NOTHING",
                    id,
                )
        return _record(row)

    async def load(self, id: str) -> SessionRecord | None:
        """Load one session record from Postgres.

        Args:
            id: Session identifier to look up.

        Returns:
            The session record, or ``None`` when the ID is unknown.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            row = await conn.fetchrow(
                "SELECT id, created_at, updated_at, meta, invoked_skills "
                "FROM sessions WHERE id = $1",
                id,
            )
        return _record(row) if row else None

    async def load_messages(self, id: str) -> list[StoredMessage]:
        """Load a session's stored messages in ascending sequence order.

        Args:
            id: Session identifier whose messages should be loaded.

        Returns:
            Stored messages ordered by their per-session sequence number.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            rows = await conn.fetch(
                "SELECT seq, appended_at, message FROM messages WHERE session_id = $1 ORDER BY seq",
                id,
            )
        return [
            StoredMessage(
                seq=row["seq"],
                appended_at=row["appended_at"],
                message=message_from_dict(json.loads(row["message"])),
            )
            for row in rows
        ]

    async def append_messages(self, id: str, messages: list[Message]) -> list[StoredMessage]:
        """Atomically append messages in input order with consecutive sequences.

        Args:
            id: Session identifier receiving the messages.
            messages: Messages to append in provider order.

        Returns:
            Stored rows for the appended messages in input order.

        Raises:
            KeyError: If the session does not exist.
        """

        if not messages:
            return []
        pool = await self._ensure()
        ts = now_iso()
        encoded = [dumps(message_to_dict(message)) for message in messages]
        async with pool.acquire() as conn:
            row = await conn.fetchrow(
                """
                WITH updated AS (
                    UPDATE sessions
                    SET updated_at = $2,
                        last_message_seq = last_message_seq + cardinality($3::text[])
                    WHERE id = $1
                    RETURNING id,
                              last_message_seq - cardinality($3::text[]) AS first_seq
                ), inserted AS (
                    INSERT INTO messages (session_id, seq, appended_at, message)
                    SELECT updated.id, updated.first_seq + ordinality, $2, message_json
                    FROM updated
                    CROSS JOIN unnest($3::text[])
                        WITH ORDINALITY AS messages(message_json, ordinality)
                    RETURNING seq
                )
                SELECT (SELECT id FROM updated) AS session_id,
                       COALESCE(
                           (SELECT array_agg(seq ORDER BY seq) FROM inserted),
                           ARRAY[]::BIGINT[]
                       ) AS allocated_seqs
                """,
                id,
                ts,
                encoded,
            )
            if row is None or row["session_id"] is None:
                raise KeyError(f"session not found: {id}")
        seqs = [int(seq) for seq in row["allocated_seqs"]]
        return [
            StoredMessage(seq=seq, appended_at=ts, message=message)
            for seq, message in zip(seqs, messages, strict=True)
        ]

    async def enqueue_inbox(self, id: str, delivery: InboxDelivery) -> None:
        """Durably enqueue one inbox delivery with digest deduplication.

        Args:
            id: Session identifier receiving the delivery.
            delivery: Delivery receipt and message payload to enqueue.

        Repeating a delivery ID with the same digest is an idempotent no-op;
        a different digest is rejected inside the transaction.

        Raises:
            KeyError: If the session does not exist.
            ConfigError: If the delivery ID conflicts with a stored digest.
        """

        pool = await self._ensure()
        message_json, source, metadata_json = encode_inbox_delivery(delivery)
        async with pool.acquire() as conn:
            async with conn.transaction():
                await _lock_session_pg(conn, id)
                inserted = await conn.fetchval(
                    """
                    INSERT INTO session_inbox (
                        session_id, delivery_id, digest, enqueued_at,
                        message, source, metadata_json, message_seq
                    ) VALUES ($1, $2, $3, $4, $5, $6, $7, null)
                    ON CONFLICT (session_id, delivery_id) DO NOTHING
                    RETURNING digest
                    """,
                    id,
                    delivery.delivery_id,
                    delivery.digest,
                    now_iso(),
                    message_json,
                    source,
                    metadata_json,
                )
                if inserted is None:
                    existing = await conn.fetchval(
                        "SELECT digest FROM session_inbox "
                        "WHERE session_id = $1 AND delivery_id = $2",
                        id,
                        delivery.delivery_id,
                    )
                    if existing != delivery.digest:
                        raise ConfigError(
                            f"conflicting inbox delivery {delivery.delivery_id!r} "
                            f"for session {id!r}"
                        )

    async def commit_inbox(self, id: str, *, after_seq: int) -> list[StoredMessage]:
        """Atomically commit pending inbox rows and return messages after a cursor.

        Args:
            id: Session identifier whose inbox should be committed.
            after_seq: Exclusive message sequence cursor for returned rows.

        Returns:
            Stored messages with sequence numbers greater than ``after_seq``.

        Raises:
            KeyError: If the session does not exist or a stored message omits
                a required field.
            ConfigError: If ``after_seq`` is invalid or a pending row has no
                message payload, or the decoded payload is not an object.
            json.JSONDecodeError: If a stored message's JSON is malformed.
            TypeError: If a stored message field has an incompatible shape.
            ValueError: If a stored message contains an unknown content-block
                type.
        """

        if isinstance(after_seq, bool) or not isinstance(after_seq, int) or after_seq < 0:
            raise ConfigError("after_seq must be a non-negative integer")
        pool = await self._ensure()
        async with pool.acquire() as conn:
            async with conn.transaction():
                await _lock_session_pg(conn, id)
                pending = await conn.fetch(
                    """
                    SELECT delivery_id, message FROM session_inbox
                    WHERE session_id = $1 AND message_seq IS NULL
                    ORDER BY inbox_seq
                    """,
                    id,
                )
                cur_seq = await _current_message_seq_pg(conn, id)
                for row in pending:
                    if row["message"] is None:  # pragma: no cover - database corruption guard
                        raise ConfigError("pending inbox delivery has no message payload")
                    decode_inbox_message(row["message"])
                if pending:
                    ts = now_iso()
                    for row in pending:
                        payload = row["message"]
                        cur_seq += 1
                        await conn.execute(
                            "INSERT INTO messages (session_id, seq, appended_at, message) "
                            "VALUES ($1, $2, $3, $4)",
                            id,
                            cur_seq,
                            ts,
                            payload,
                        )
                        await conn.execute(
                            """
                            UPDATE session_inbox
                            SET message_seq = $1, message = null,
                                source = null, metadata_json = null
                            WHERE session_id = $2 AND delivery_id = $3
                            """,
                            cur_seq,
                            id,
                            row["delivery_id"],
                        )
                    await conn.execute(
                        "UPDATE sessions SET updated_at = $1, last_message_seq = $2 WHERE id = $3",
                        ts,
                        cur_seq,
                        id,
                    )
                rows = await conn.fetch(
                    """
                    SELECT seq, appended_at, message FROM messages
                    WHERE session_id = $1 AND seq > $2 ORDER BY seq
                    """,
                    id,
                    after_seq,
                )
                return [
                    StoredMessage(
                        seq=row["seq"],
                        appended_at=row["appended_at"],
                        message=message_from_dict(json.loads(row["message"])),
                    )
                    for row in rows
                ]

    async def save_provider_snapshot(self, id: str, snapshot: ProviderViewSnapshot) -> None:
        """Persist the latest compacted provider-view snapshot.

        Args:
            id: Session identifier owning the snapshot.
            snapshot: Provider projection and message watermark to store.
        """

        pool = await self._ensure()
        payload = json.dumps(snapshot_to_dict(snapshot))
        async with pool.acquire() as conn:
            await conn.execute(
                """
                INSERT INTO session_snapshots (session_id, snapshot, updated_at)
                VALUES ($1, $2, $3)
                ON CONFLICT (session_id) DO UPDATE
                    SET snapshot = EXCLUDED.snapshot, updated_at = EXCLUDED.updated_at
                """,
                id,
                payload,
                now_iso(),
            )

    async def load_provider_snapshot(self, id: str) -> ProviderViewSnapshot | None:
        """Load a previously persisted provider-view snapshot.

        Args:
            id: Session identifier whose snapshot should be loaded.

        Returns:
            The stored snapshot, or ``None`` when none exists.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            row = await conn.fetchrow(
                "SELECT snapshot FROM session_snapshots WHERE session_id = $1", id
            )
        return snapshot_from_dict(json.loads(row["snapshot"])) if row is not None else None

    async def save_offload(self, id: str, path: str, content: str) -> None:
        """Persist or replace one offloaded tool result for a session.

        Args:
            id: Session identifier owning the offloaded result.
            path: Normalized virtual path the model was given.
            content: Full tool-result text.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            await conn.execute(
                """
                INSERT INTO session_offloads (session_id, path, content)
                VALUES ($1, $2, $3)
                ON CONFLICT (session_id, path) DO UPDATE SET content = EXCLUDED.content
                """,
                id,
                path,
                content,
            )

    async def load_offload(self, id: str, path: str) -> str | None:
        """Load one offloaded tool result.

        Args:
            id: Session identifier owning the offloaded result.
            path: Normalized virtual path to load.

        Returns:
            The stored text, or ``None`` when the session has no such result.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            return await conn.fetchval(
                "SELECT content FROM session_offloads WHERE session_id = $1 AND path = $2",
                id,
                path,
            )

    async def list_offloads(self, id: str) -> list[str]:
        """List a session's offloaded-result paths.

        Args:
            id: Session identifier whose offloaded results should be listed.

        Returns:
            Sorted virtual paths.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            rows = await conn.fetch(
                "SELECT path FROM session_offloads WHERE session_id = $1 ORDER BY path", id
            )
        return [row["path"] for row in rows]

    async def update_meta(self, id: str, meta: dict[str, object]) -> SessionRecord:
        """Merge metadata into a session in one transaction.

        Args:
            id: Session identifier whose metadata should be updated.
            meta: Metadata keys and values to merge.

        Returns:
            The updated session record after the transaction commits.

        Raises:
            KeyError: If the session does not exist.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            async with conn.transaction():
                row = await conn.fetchrow(
                    "SELECT id, created_at, updated_at, meta, invoked_skills "
                    "FROM sessions WHERE id = $1",
                    id,
                )
                if row is None:
                    raise KeyError(f"session not found: {id}")
                existing = json.loads(row["meta"])
                existing.update(meta)
                ts = now_iso()
                await conn.execute(
                    "UPDATE sessions SET updated_at = $1, meta = $2 WHERE id = $3",
                    ts,
                    json.dumps(existing),
                    id,
                )
        return SessionRecord(
            id=row["id"],
            created_at=row["created_at"],
            updated_at=ts,
            meta=existing,
            invoked_skills=list(json.loads(row["invoked_skills"] or "[]")),
        )

    async def set_invoked_skills(self, id: str, skills: list[dict[str, object]]) -> None:
        """Replace persisted invoked-skill records for a session.

        Args:
            id: Session identifier whose records should be replaced.
            skills: Skill records to store.

        Raises:
            KeyError: If the session does not exist.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            updated = await conn.fetchval(
                "UPDATE sessions SET invoked_skills = $1, updated_at = $2 WHERE id = $3 "
                "RETURNING id",
                json.dumps(skills),
                now_iso(),
                id,
            )
            if updated is None:
                raise KeyError(f"session not found: {id}")

    async def list(self, *, limit: int | None = None, offset: int = 0) -> list[SessionRecord]:
        """List sessions ordered by descending update timestamp.

        Args:
            limit: Maximum number of records, or ``None`` for all records.
            offset: Number of newest records to skip.

        Returns:
            Matching session records in newest-updated-first order.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            if limit is not None:
                rows = await conn.fetch(
                    "SELECT id, created_at, updated_at, meta, invoked_skills "
                    "FROM sessions ORDER BY updated_at DESC LIMIT $1 OFFSET $2",
                    limit,
                    offset,
                )
            else:
                rows = await conn.fetch(
                    "SELECT id, created_at, updated_at, meta, invoked_skills "
                    "FROM sessions ORDER BY updated_at DESC OFFSET $1",
                    offset,
                )
        return [_record(row) for row in rows]

    async def delete(self, id: str) -> None:
        """Delete a session and all related persisted state in one transaction.

        Args:
            id: Session identifier to delete.

        Deleting an unknown ID is an idempotent no-op.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            async with conn.transaction():
                await conn.execute("DELETE FROM task_edges WHERE session_id = $1", id)
                await conn.execute("DELETE FROM tasks WHERE session_id = $1", id)
                await conn.execute("DELETE FROM task_counters WHERE session_id = $1", id)
                await conn.execute("DELETE FROM session_snapshots WHERE session_id = $1", id)
                await conn.execute("DELETE FROM session_inbox WHERE session_id = $1", id)
                await conn.execute("DELETE FROM session_offloads WHERE session_id = $1", id)
                await conn.execute("DELETE FROM messages WHERE session_id = $1", id)
                await conn.execute("DELETE FROM sessions WHERE id = $1", id)

    async def create_task(self, session_id: str, input: CreateTaskInput) -> Task:
        """Create a pending task with a transactionally allocated ID.

        Args:
            session_id: Session that owns the task.
            input: Task fields to persist.

        Returns:
            The newly created task after its transaction commits.

        Raises:
            KeyError: If the session does not exist.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            async with conn.transaction():
                await _lock_session_pg(conn, session_id)
                task_id = await _allocate_task_id_pg(conn, session_id)
                now = now_iso()
                await conn.execute(
                    """
                    INSERT INTO tasks (
                        session_id, id, subject, description, active_form,
                        status, owner, metadata_json, created_at, updated_at
                    ) VALUES ($1,$2,$3,$4,$5,'pending',null,$6,$7,$8)
                    """,
                    session_id,
                    task_id,
                    input.subject,
                    input.description,
                    input.active_form,
                    json.dumps(input.metadata or {}),
                    now,
                    now,
                )
                await conn.execute(
                    "UPDATE sessions SET updated_at = $1 WHERE id = $2",
                    now,
                    session_id,
                )
                result = await _get_task_pg(conn, session_id, task_id)
        if result is None:
            raise KeyError(f"task not found after create: {task_id}")
        return result

    async def get_task(self, session_id: str, task_id: str) -> Task | None:
        """Load one task by session and task ID.

        Args:
            session_id: Session that owns the task.
            task_id: Task identifier to look up.

        Returns:
            The task, or ``None`` when it does not exist.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            return await _get_task_pg(conn, session_id, task_id)

    async def list_tasks(self, session_id: str) -> list[Task]:
        """List a session's tasks in ascending numeric task-ID order.

        Args:
            session_id: Session whose tasks should be listed.

        Returns:
            Tasks in deterministic task-ID order.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            rows = await conn.fetch(
                """
                SELECT id, subject, description, active_form, status, owner,
                       metadata_json, created_at, updated_at
                FROM tasks WHERE session_id = $1
                ORDER BY CAST(id AS INTEGER) ASC
                """,
                session_id,
            )
            out: list[Task] = []
            for row in rows:
                tid = str(row["id"])
                blocks, blocked_by = await _load_edges_pg(conn, session_id, tid)
                out.append(_row_to_task(session_id, row, blocks, blocked_by))
        return out

    async def update_task(self, session_id: str, task_id: str, patch: TaskPatch) -> Task | None:
        """Apply a partial task update and dependency-edge changes transactionally.

        Args:
            session_id: Session that owns the task.
            task_id: Task identifier to update.
            patch: Fields and dependency edges to change.

        Returns:
            The updated task, or ``None`` when it does not exist or is deleted.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            async with conn.transaction():
                existing = await _get_task_pg(conn, session_id, task_id)
                if existing is None:
                    return None
                if patch.status == "deleted":
                    await _delete_task_pg(conn, session_id, task_id)
                    return None
                now = now_iso()
                if patch.subject is not None:
                    await conn.execute(
                        "UPDATE tasks SET subject=$1 WHERE session_id=$2 AND id=$3",
                        patch.subject,
                        session_id,
                        task_id,
                    )
                if patch.description is not None:
                    await conn.execute(
                        "UPDATE tasks SET description=$1 WHERE session_id=$2 AND id=$3",
                        patch.description,
                        session_id,
                        task_id,
                    )
                if patch.active_form is not None:
                    await conn.execute(
                        "UPDATE tasks SET active_form=$1 WHERE session_id=$2 AND id=$3",
                        patch.active_form,
                        session_id,
                        task_id,
                    )
                if patch.status is not None:
                    await conn.execute(
                        "UPDATE tasks SET status=$1 WHERE session_id=$2 AND id=$3",
                        patch.status,
                        session_id,
                        task_id,
                    )
                if patch.owner is not None:
                    await conn.execute(
                        "UPDATE tasks SET owner=$1 WHERE session_id=$2 AND id=$3",
                        patch.owner,
                        session_id,
                        task_id,
                    )
                if patch.metadata is not None:
                    md = dict(existing.metadata)
                    for k, v in patch.metadata.items():
                        if v is None:
                            md.pop(k, None)
                        else:
                            md[k] = v
                    await conn.execute(
                        "UPDATE tasks SET metadata_json=$1 WHERE session_id=$2 AND id=$3",
                        json.dumps(md),
                        session_id,
                        task_id,
                    )
                for to_id in patch.remove_blocks or []:
                    await conn.execute(
                        "DELETE FROM task_edges WHERE session_id=$1 "
                        "AND from_task_id=$2 AND to_task_id=$3",
                        session_id,
                        task_id,
                        to_id,
                    )
                for from_id in patch.remove_blocked_by or []:
                    await conn.execute(
                        "DELETE FROM task_edges WHERE session_id=$1 "
                        "AND from_task_id=$2 AND to_task_id=$3",
                        session_id,
                        from_id,
                        task_id,
                    )
                for to_id in patch.add_blocks or []:
                    await conn.execute(
                        "INSERT INTO task_edges "
                        "(session_id, from_task_id, to_task_id, kind) "
                        "VALUES ($1,$2,$3,'blocks') ON CONFLICT DO NOTHING",
                        session_id,
                        task_id,
                        to_id,
                    )
                for from_id in patch.add_blocked_by or []:
                    await conn.execute(
                        "INSERT INTO task_edges "
                        "(session_id, from_task_id, to_task_id, kind) "
                        "VALUES ($1,$2,$3,'blocks') ON CONFLICT DO NOTHING",
                        session_id,
                        from_id,
                        task_id,
                    )
                await conn.execute(
                    "UPDATE tasks SET updated_at=$1 WHERE session_id=$2 AND id=$3",
                    now,
                    session_id,
                    task_id,
                )
                await conn.execute(
                    "UPDATE sessions SET updated_at=$1 WHERE id=$2",
                    now,
                    session_id,
                )
                return await _get_task_pg(conn, session_id, task_id)

    async def delete_task(self, session_id: str, task_id: str) -> bool:
        """Delete a task and remove its dependency edges transactionally.

        Args:
            session_id: Session that owns the task.
            task_id: Task identifier to delete.

        Returns:
            ``True`` when a task was deleted, otherwise ``False``.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            async with conn.transaction():
                return await _delete_task_pg(conn, session_id, task_id)

    async def claim_task(self, session_id: str, task_id: str, owner: str) -> Task | None:
        """Atomically claim one pending, unowned task for an owner.

        Args:
            session_id: Session that owns the task.
            task_id: Task identifier to claim.
            owner: Owner identity to record on success.

        Returns:
            The claimed task, or ``None`` when it is unavailable to this caller.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            async with conn.transaction():
                ts = now_iso()
                # Row-level conditional update: only one concurrent claimer wins.
                claimed = await conn.fetchrow(
                    """
                    UPDATE tasks SET owner=$1, updated_at=$2
                    WHERE session_id=$3 AND id=$4 AND owner IS NULL AND status='pending'
                    RETURNING id
                    """,
                    owner,
                    ts,
                    session_id,
                    task_id,
                )
                if claimed is None:
                    return None
                await conn.execute("UPDATE sessions SET updated_at=$1 WHERE id=$2", ts, session_id)
                return await _get_task_pg(conn, session_id, task_id)

    async def ready_tasks(self, session_id: str) -> list[Task]:
        """List pending, unowned tasks whose dependencies are complete.

        Args:
            session_id: Session whose ready tasks should be listed.

        Returns:
            Ready tasks in ascending numeric task-ID order.
        """

        tasks = await self.list_tasks(session_id)
        by_id = {t.id: t for t in tasks}
        return [
            t
            for t in tasks
            if t.status == "pending"
            and t.owner is None
            and all(
                by_id.get(b) is not None and by_id[b].status == "completed" for b in t.blocked_by
            )
        ]

    async def release_task(self, session_id: str, task_id: str) -> Task | None:
        """Release a task owner and reset unfinished tasks to pending.

        Args:
            session_id: Session that owns the task.
            task_id: Task identifier to release.

        Returns:
            The released task, or ``None`` when it does not exist. Completed
            tasks are returned unchanged.
        """

        pool = await self._ensure()
        async with pool.acquire() as conn:
            async with conn.transaction():
                task = await _get_task_pg(conn, session_id, task_id)
                if task is None:
                    return None
                if task.status == "completed":
                    return task  # don't resurrect a finished task
                now = now_iso()
                await conn.execute(
                    "UPDATE tasks SET owner=null, status='pending', updated_at=$1 "
                    "WHERE session_id=$2 AND id=$3",
                    now,
                    session_id,
                    task_id,
                )
                await conn.execute("UPDATE sessions SET updated_at=$1 WHERE id=$2", now, session_id)
                return await _get_task_pg(conn, session_id, task_id)

    async def close(self) -> None:
        """Close this store's owned pool.

        Caller-supplied pools are retained; their host owns their lifecycle.
        """

        await close_pool(self)


# ── Async PG helpers (run within an acquired connection) ────────────────────


async def _lock_session_pg(conn: Any, session_id: str) -> None:
    """Lock the parent session row for transaction-scoped allocation.

    PostgreSQL row locks are released automatically on commit/rollback.  Using
    the parent row avoids process-local locks and works across every pool and
    worker connected to the database.
    """
    found = await conn.fetchval(
        "SELECT id FROM sessions WHERE id = $1 FOR UPDATE",
        session_id,
    )
    if found is None:
        raise KeyError(f"session not found: {session_id}")


async def _current_message_seq_pg(conn: Any, session_id: str) -> int:
    value = await conn.fetchval(
        "SELECT last_message_seq FROM sessions WHERE id = $1",
        session_id,
    )
    return int(value or 0)


async def _allocate_task_id_pg(conn: Any, session_id: str) -> str:
    """Atomically reserve the next numeric task id for *session_id*.

    The caller holds the session-row lock.  The upsert also makes allocation
    safe for databases upgraded from a partial/older schema where the counter
    row is missing.
    """
    allocated = await conn.fetchval(
        """
        INSERT INTO task_counters (session_id, next_id)
        SELECT $1, COALESCE(MAX(id::BIGINT), 0) + 2
        FROM tasks
        WHERE session_id = $1 AND id ~ '^[0-9]+$'
        ON CONFLICT (session_id) DO UPDATE
            SET next_id = task_counters.next_id + 1
        RETURNING next_id - 1
        """,
        session_id,
    )
    if allocated is None:  # pragma: no cover - INSERT ... RETURNING invariant
        raise RuntimeError(f"failed to allocate task id for session: {session_id}")
    return str(int(allocated))


def _record(row: Any) -> SessionRecord:
    return SessionRecord(
        id=row["id"],
        created_at=row["created_at"],
        updated_at=row["updated_at"],
        meta=json.loads(row["meta"]),
        invoked_skills=list(json.loads(row["invoked_skills"] or "[]")),
    )


def _row_to_task(
    session_id: str,
    row: Any,
    blocks: list[str],
    blocked_by: list[str],
) -> Task:
    return Task(
        id=str(row["id"]),
        session_id=session_id,
        subject=row["subject"],
        description=row["description"],
        active_form=row["active_form"],
        status=row["status"],  # type: ignore[arg-type]
        owner=row["owner"],
        blocks=blocks,
        blocked_by=blocked_by,
        metadata=dict(json.loads(row["metadata_json"] or "{}")),
        created_at=row["created_at"],
        updated_at=row["updated_at"],
    )


async def _load_edges_pg(conn: Any, session_id: str, task_id: str) -> tuple[list[str], list[str]]:
    blocks = [
        str(r["to_task_id"])
        for r in await conn.fetch(
            "SELECT to_task_id FROM task_edges WHERE session_id=$1 AND from_task_id=$2",
            session_id,
            task_id,
        )
    ]
    blocked_by = [
        str(r["from_task_id"])
        for r in await conn.fetch(
            "SELECT from_task_id FROM task_edges WHERE session_id=$1 AND to_task_id=$2",
            session_id,
            task_id,
        )
    ]
    return blocks, blocked_by


async def _get_task_pg(conn: Any, session_id: str, task_id: str) -> Task | None:
    row = await conn.fetchrow(
        """
        SELECT id, subject, description, active_form, status, owner,
               metadata_json, created_at, updated_at
        FROM tasks WHERE session_id = $1 AND id = $2
        """,
        session_id,
        task_id,
    )
    if row is None:
        return None
    blocks, blocked_by = await _load_edges_pg(conn, session_id, task_id)
    return _row_to_task(session_id, row, blocks, blocked_by)


async def _delete_task_pg(conn: Any, session_id: str, task_id: str) -> bool:
    await conn.execute(
        "DELETE FROM task_edges WHERE session_id=$1 AND (from_task_id=$2 OR to_task_id=$2)",
        session_id,
        task_id,
    )
    result = await conn.execute(
        "DELETE FROM tasks WHERE session_id=$1 AND id=$2",
        session_id,
        task_id,
    )
    await conn.execute(
        "UPDATE sessions SET updated_at=$1 WHERE id=$2",
        now_iso(),
        session_id,
    )
    # asyncpg DELETE returns "DELETE N" — extract count
    try:
        count = int(result.split()[-1])
    except (ValueError, IndexError, AttributeError):
        count = 0
    return count > 0
